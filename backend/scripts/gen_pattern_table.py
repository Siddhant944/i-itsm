"""Generate the report's OOP and design-pattern evidence from the code (P6.2).

Reads ``backend/app`` with ``ast`` (nothing is imported or run) and writes:

* ``report/generated/patterns.tex`` — every module or class docstring that says
  ``Pattern: <name>. Problem solved: <text>`` (AGENTS.md asks each pattern class to name its
  pattern and the problem it solves), with its file, line and classes;
* ``report/generated/oop-evidence.tex`` — counts that back the OOP claims: abstract base
  classes, abstract methods, inheritance trees, name-mangled attributes, read-only
  properties, frozen value objects and the error hierarchy.

``tests/unit/scripts/test_pattern_table.py`` fails when a committed file is stale.
Usage: ``uv run python scripts/gen_pattern_table.py``.
"""

from __future__ import annotations

import ast
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
APP = BACKEND / "app"
OUT = BACKEND.parent / "report" / "generated"

HEADER = "% GENERATED by backend/scripts/gen_pattern_table.py from backend/app. Do not edit.\n"
_PATTERN = re.compile(r"Pattern:\s*(?P<name>.+?)\.\s+Problem solved:\s*(?P<problem>.+)", re.S)
_MANGLED = re.compile(r"self\.__([a-z]\w*)\s*[:=]")


@dataclass(frozen=True)
class PatternUse:
    pattern: str
    problem: str
    path: str
    line: int
    classes: tuple[str, ...]


def _first_sentence(text: str) -> str:
    flat = " ".join(text.split())
    match = re.match(r"(.+?[.;])(\s|$)", flat)
    sentence = (match.group(1) if match else flat).rstrip(";.") + "."
    return sentence[:1].upper() + sentence[1:]


def _modules() -> list[tuple[str, ast.Module]]:
    found = []
    for path in sorted(APP.rglob("*.py")):
        rel = path.relative_to(BACKEND.parent).as_posix()
        found.append((rel, ast.parse(path.read_text(encoding="utf-8"), filename=rel)))
    return found


def _public_classes(tree: ast.Module) -> list[ast.ClassDef]:
    return [n for n in tree.body if isinstance(n, ast.ClassDef) and not n.name.startswith("_")]


def _base_names(node: ast.ClassDef) -> list[str]:
    names = []
    for base in node.bases:
        if isinstance(base, ast.Name):
            names.append(base.id)
        elif isinstance(base, ast.Attribute):
            names.append(base.attr)
        elif isinstance(base, ast.Subscript) and isinstance(base.value, ast.Name):
            names.append(base.value.id)
    return names


def _key_classes(tree: ast.Module, limit: int = 6) -> tuple[str, ...]:
    """A module's main classes: ABCs and what extends them first, then the rest."""
    classes = _public_classes(tree)
    local = {c.name for c in classes}
    abcs = [c.name for c in classes if "ABC" in _base_names(c)]
    children = [c.name for c in classes if set(_base_names(c)) & local and c.name not in abcs]
    rest = [c.name for c in classes if c.name not in abcs and c.name not in children]
    ordered = [*abcs, *children, *rest]
    return tuple(ordered[:limit]) + (("...",) if len(ordered) > limit else ())


def pattern_uses() -> list[PatternUse]:
    uses: list[PatternUse] = []
    for rel, tree in _modules():
        doc = ast.get_docstring(tree)
        if doc and (m := _PATTERN.search(doc)):
            uses.append(
                PatternUse(
                    " ".join(m["name"].split()),
                    _first_sentence(m["problem"]),
                    rel,
                    1,
                    _key_classes(tree),
                )
            )
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                cdoc = ast.get_docstring(node)
                if cdoc and (m := _PATTERN.search(cdoc)):
                    uses.append(
                        PatternUse(
                            " ".join(m["name"].split()),
                            _first_sentence(m["problem"]),
                            rel,
                            node.lineno,
                            (node.name,),
                        )
                    )
    return sorted(uses, key=lambda u: (u.pattern.lower(), u.path))


@dataclass(frozen=True)
class Evidence:
    concept: str
    measure: str
    examples: str


def oop_evidence() -> list[Evidence]:
    modules = _modules()
    classes: list[tuple[str, ast.ClassDef]] = [
        (rel, node)
        for rel, tree in modules
        for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef)
    ]
    parents = {node.name: _base_names(node) for _, node in classes}

    def descends(name: str, root: str) -> bool:
        seen: set[str] = set()
        stack = [name]
        while stack:
            current = stack.pop()
            if current == root:
                return True
            if current in seen:
                continue
            seen.add(current)
            stack.extend(parents.get(current, []))
        return False

    abcs = [n for _, n in classes if "ABC" in _base_names(n)]
    abstract_methods = sum(
        1
        for _, n in classes
        for f in n.body
        if isinstance(f, ast.FunctionDef)
        and any(isinstance(d, ast.Name) and d.id == "abstractmethod" for d in f.decorator_list)
    )
    properties = sum(
        1
        for _, n in classes
        for f in n.body
        if isinstance(f, ast.FunctionDef)
        and any(isinstance(d, ast.Name) and d.id == "property" for d in f.decorator_list)
    )
    setters = sum(
        1
        for _, n in classes
        for f in n.body
        if isinstance(f, ast.FunctionDef)
        and any(isinstance(d, ast.Attribute) and d.attr == "setter" for d in f.decorator_list)
    )
    frozen = [
        n.name
        for _, n in classes
        for d in n.decorator_list
        if isinstance(d, ast.Call)
        and getattr(d.func, "id", getattr(d.func, "attr", "")) == "dataclass"
        and any(k.arg == "frozen" and getattr(k.value, "value", False) for k in d.keywords)
    ]
    mangled = Counter[str]()
    for rel, _ in modules:
        text = (BACKEND.parent / rel).read_text(encoding="utf-8")
        mangled.update({rel: len(set(_MANGLED.findall(text)))})
    mangled_total = sum(mangled.values())
    users = sorted(n.name for _, n in classes if descends(n.name, "User") and n.name != "User")
    states = sorted(
        n.name
        for _, n in classes
        if descends(n.name, "IncidentState")
        and n.name != "IncidentState"
        and not n.name.startswith("_")
    )
    errors = [n.name for _, n in classes if descends(n.name, "ITSMError") and n.name != "ITSMError"]
    error_groups = [n.name for _, n in classes if parents.get(n.name) == ["ITSMError"]]
    implementations = sum(
        1 for _, n in classes if any(b in {a.name for a in abcs} for b in _base_names(n))
    )
    return [
        Evidence(
            "Abstraction and interfaces",
            f"{len(abcs)} abstract base classes declaring {abstract_methods} abstract methods; "
            f"{implementations} classes implement one directly",
            "Clock, IncidentState, PriorityStrategy, AssignmentStrategy, RiskEstimator, "
            "AIAdvisor, NotificationChannel, IncidentRepository, UnitOfWork",
        ),
        Evidence(
            "Encapsulation",
            f"{mangled_total} name-mangled attributes (self.__x) in "
            f"{sum(1 for v in mangled.values() if v)} modules, read through {properties} "
            f"properties; {setters} property setters",
            "Incident, SLAClock, User, Technician, IncidentService",
        ),
        Evidence(
            "Immutability (value objects)",
            f"{len(frozen)} frozen dataclasses",
            ", ".join(sorted(frozen)[:8]) + ", ...",
        ),
        Evidence(
            "Inheritance (true is-a only)",
            f"User has {len(users)} subclasses; IncidentState has {len(states)} concrete states; "
            f"ITSMError has {len(error_groups)} groups and "
            f"{len(errors) - len(error_groups)} specific errors",
            ", ".join(users),
        ),
        Evidence(
            "Polymorphism",
            "one call, many behaviours, chosen at runtime",
            "state.resolve(), strategy.rank(), channel.send(), advisor.classify(), clock.now()",
        ),
    ]


_TEX = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "_": r"\_",
    "#": r"\#",
    "$": r"\$",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_UNICODE = {"→": r"$\rightarrow$", "×": r"$\times$", "≥": r"$\geq$", "≤": r"$\leq$", "…": "..."}


def tex(text: str) -> str:
    out = "".join(_TEX.get(ch, ch) for ch in text)
    out = out.replace("``", "").replace("`", "")
    for char, replacement in _UNICODE.items():
        out = out.replace(char, replacement)
    return out


def _code(text: str) -> str:
    return r"\texttt{\small " + tex(text).replace("/", r"/\allowbreak{}") + "}"


def patterns_tex() -> str:
    rows = [
        HEADER.rstrip(),
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{2.6cm}"
        r">{\raggedright\arraybackslash}p{6.6cm}>{\raggedright\arraybackslash}p{6.4cm}@{}}",
        r"\toprule",
        r"Pattern & Problem it solves (from the docstring) & Where \\",
        r"\midrule",
        r"\endhead",
    ]
    for use in pattern_uses():
        where = _code(f"{use.path}:{use.line}") + r" \newline " + tex(", ".join(use.classes))
        rows.append(f"{tex(use.pattern)} & {tex(use.problem)} & {where} " + r"\\")
    rows += [r"\bottomrule", r"\end{longtable}", ""]
    return "\n".join(rows)


def oop_tex() -> str:
    rows = [
        HEADER.rstrip(),
        r"\begin{tabularx}{\textwidth}{@{}p{3.2cm}XX@{}}",
        r"\toprule",
        r"Concept & Measured in the code & Examples \\",
        r"\midrule",
    ]
    for e in oop_evidence():
        rows.append(f"{tex(e.concept)} & {tex(e.measure)} & {tex(e.examples)} " + r"\\")
    rows += [r"\bottomrule", r"\end{tabularx}", ""]
    return "\n".join(rows)


def render_all() -> dict[str, str]:
    return {"patterns.tex": patterns_tex(), "oop-evidence.tex": oop_tex()}


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.mkdir(parents=True, exist_ok=True)
    for name, text in render_all().items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_pattern_table: wrote {', '.join(render_all())} to {out}")


if __name__ == "__main__":
    main()
