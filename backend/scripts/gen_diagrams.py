def transitions() -> list[tuple[IncidentStatus, IncidentStatus, str]]:
    """Every (from, to, trigger) the State classes allow, found by calling each trigger."""
    found: list[tuple[IncidentStatus, IncidentStatus, str]] = []
    for status in IncidentStatus:
        state: IncidentState = state_for(status)
        for method, label in TRIGGERS:
            try:
                target = getattr(state, method)()
            except InvalidStateTransitionError:
                continue
            found.append((status, target, label))
    return found


def state_diagram() -> str:
    """The lifecycle as a PlantUML state diagram; arrows sharing ends share one label."""
    merged: dict[tuple[IncidentStatus, IncidentStatus], list[str]] = {}
    for source, target, label in transitions():
        merged.setdefault((source, target), []).append(label)
    lines = ["@startuml state", HEADER, LAYOUT, STYLE]
    lines.append("title Incident lifecycle (State pattern): the transitions the code allows\n")
    for status in IncidentStatus:
        cls = type(state_for(status)).__name__
        lines.append(f"state {status.value} : {cls}")
    lines.append("[*] --> NEW : report")
    for (source, target), labels in merged.items():
        lines.append(f"{source.value} --> {target.value} : {' / '.join(labels)}")
    lines.append("CLOSED --> [*]")
    lines.append("CANCELLED --> [*]")
    lines.append(
        f"note as N\n  {len(set(merged))} distinct (from, to) pairs; any other trigger raises\n"
        "  InvalidStateTransitionError (409). CANCELLED is reachable from every\n"
        "  non-terminal state up to ON_HOLD.\nend note"
    )
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- ER diagram


def _column_type(column: Column[Any]) -> str:
    try:
        name = str(column.type.compile())
    except Exception:  # a custom type without a compile rule for the default dialect
        name = type(column.type).__name__
    return name.split("(")[0].upper().replace("VARCHAR", "VARCHAR")


def _column_line(column: Column[Any]) -> str:
    marks = []
    if column.primary_key:
        marks.append("PK")
    if column.foreign_keys:
        marks.append("FK")
    if column.unique:
        marks.append("UQ")
    prefix = "* " if column.primary_key or not column.nullable else "  "
    tag = f" <<{','.join(marks)}>>" if marks else ""
    return f"  {prefix}{column.name} : {_column_type(column)}{tag}"


def er_diagram() -> str:
    """Every table, its columns and its foreign keys, from the ORM metadata."""
    tables: Sequence[Table] = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    lines = ["@startuml er", HEADER, LAYOUT, STYLE.replace("skinparam linetype ortho\n", "")]
    lines.append(f"title Database schema: {len(tables)} tables (* = NOT NULL)\n")
    for table in tables:
        lines.append(f"entity {table.name} {{")
        pk = [c for c in table.columns if c.primary_key]
        rest = [c for c in table.columns if not c.primary_key]
        lines.extend(_column_line(c) for c in pk)
        lines.append("  --")
        lines.extend(_column_line(c) for c in rest)
        lines.append("}")
    seen: set[tuple[str, str, str]] = set()
    for table in tables:
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            target = fk.column.table.name
            key = (table.name, target, fk.parent.name)
            if key in seen:
                continue
            seen.add(key)
            # Parent end: exactly one, or zero-or-one when the key may be NULL.
            parent_end = "|o" if fk.parent.nullable else "||"
            # Child end: zero-or-one when the key is unique (or the whole primary key).
            sole_pk = [c.name for c in table.primary_key.columns] == [fk.parent.name]
            child_end = "o|" if fk.parent.unique or sole_pk else "o{"
            lines.append(f"{target} {parent_end}--{child_end} {table.name} : {fk.parent.name}")
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- class diagrams

_QUALIFIER = re.compile(r"\b(?:[A-Za-z_]\w*\.)+(?=[A-Za-z_])")


def _type_name(annotation: Any) -> str:
    """A short, readable type: no module paths, ``Optional`` written as ``X | None``."""
    if annotation is inspect.Parameter.empty or annotation is inspect.Signature.empty:
        return ""
    if isinstance(annotation, str):
        text = annotation
    elif isinstance(annotation, type) and not getattr(annotation, "__args__", None):
        text = annotation.__qualname__
    else:
        text = repr(annotation)
    text = _QUALIFIER.sub("", text.replace("<class '", "").replace("'>", ""))
    return text.replace("NoneType", "None")


def _signature(func: Callable[..., Any]) -> str:
    try:
        sig = inspect.signature(func)
    except (TypeError, ValueError):
        return "()"
    params = [
        p.name
        for p in sig.parameters.values()
        if p.name not in {"self", "cls"} and p.kind is not inspect.Parameter.VAR_KEYWORD
    ]
    if len(params) > 4:  # keep the box readable: Incident.restore takes 25
        params = [*params[:3], "..."]
    returns = _type_name(sig.return_annotation)
    return f"({', '.join(params)})" + (f" : {returns}" if returns and returns != "None" else "")


def _stereotype(cls: type) -> tuple[str, str]:
    """The PlantUML keyword and stereotype for a class."""
    if issubclass(cls, enum.Enum):
        return "enum", ""
    abstract_methods: frozenset[str] = getattr(cls, "__abstractmethods__", frozenset())
    if inspect.isabstract(cls):
        public = [
            n
            for n, v in vars(cls).items()
            if not n.startswith("_") and (callable(v) or isinstance(v, property))
        ]
        if public and all(n in abstract_methods for n in public):
            return "interface", ""
        return "abstract class", ""
    if dataclasses.is_dataclass(cls):
        params = getattr(cls, "__dataclass_params__", None)
        return "class", " <<value object>>" if params is not None and params.frozen else ""
    return "class", ""


@dataclass(frozen=True)
class ClassSpec:
    """One class to draw: ``members`` is "full", "methods" (no attributes) or "none"."""

    path: str
    members: str = "full"


@dataclass(frozen=True)
class ClassDiagram:
    """A class diagram: the classes to draw and the associations Python cannot infer."""

    name: str
    title: str
    classes: tuple[ClassSpec, ...]
    relations: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()
    direction: str = "top to bottom direction"
    packages: dict[str, tuple[str, ...]] = field(default_factory=dict)


def _load(path: str) -> type:
    module, _, name = path.rpartition(".")
    value = getattr(importlib.import_module(module), name)
    if not isinstance(value, type):
        raise TypeError(f"{path} is not a class")
    return value


def _members(cls: type, mode: str) -> list[str]:
    if mode == "none":
        return []
    lines: list[str] = []
    if issubclass(cls, enum.Enum):
        return [m.name for m in cls]
    abstract: frozenset[str] = getattr(cls, "__abstractmethods__", frozenset())
    own = vars(cls)
    if mode == "full":
        if dataclasses.is_dataclass(cls):
            for f in dataclasses.fields(cls):
                if f.name in own.get("__dataclass_fields__", {}) and not f.name.startswith("_"):
                    lines.append(f"  +{f.name} : {_type_name(f.type)}")
        for name, value in own.items():
            if isinstance(value, property) and not name.startswith("_"):
                returns = _type_name(inspect.signature(value.fget).return_annotation)  # type: ignore[arg-type]
                marker = "{abstract} " if name in abstract else ""
                lines.append(f"  {marker}+{name} : {returns} {{readOnly}}")
        annotations = own.get("__annotations__", {})
        if not dataclasses.is_dataclass(cls):
            for name, annotation in annotations.items():
                if not name.startswith("_"):
                    lines.append(f"  +{name} : {_type_name(annotation)}")
    for name, value in own.items():
        if name.startswith("_") and name != "__init__":
            continue
        if name == "__init__" or isinstance(value, property):
            continue
        if isinstance(value, staticmethod | classmethod):
            lines.append(f"  {{static}} +{name}{_signature(value.__func__)}")
        elif inspect.isfunction(value):
            marker = "{abstract} " if name in abstract else ""
            lines.append(f"  {marker}+{name}{_signature(value)}")
    return lines


def _drawn_bases(cls: type, drawn: Iterable[type]) -> list[type]:
    """The nearest drawn ancestors, skipping private helpers such as ``_Cancellable``."""
    found: list[type] = []
    for base in cls.__bases__:
        if base in drawn:
            found.append(base)
        elif base is not object:
            found.extend(b for b in _drawn_bases(base, drawn) if b not in found)
    return found


def class_diagram(spec: ClassDiagram) -> str:
    """Draw the listed classes with members and inheritance read from the code."""
    classes = {c.path: _load(c.path) for c in spec.classes}
    by_type = {cls: path for path, cls in classes.items()}
    lines = [f"@startuml {spec.name}", HEADER, LAYOUT, STYLE, spec.direction]
    lines.append(f"title {spec.title}\n")

    def emit(cs: ClassSpec) -> None:
        cls = classes[cs.path]
        keyword, stereo = _stereotype(cls)
        body = _members(cls, cs.members)
        lines.append(f"{keyword} {cls.__name__}{stereo} {{")
        lines.extend(body)
        lines.append("}")

    placed: set[str] = set()
    for package, paths in spec.packages.items():
        lines.append(f'package "{package}" {{')
        for cs in spec.classes:
            if cs.path in paths:
                emit(cs)
                placed.add(cs.path)
        lines.append("}")
    for cs in spec.classes:
        if cs.path not in placed:
            emit(cs)
    for cls in by_type:
        for base in _drawn_bases(cls, by_type):
            arrow = "..|>" if _stereotype(base)[0] == "interface" else "--|>"
            lines.append(f"{cls.__name__} {arrow} {base.__name__}")
    lines.extend(spec.relations)
    lines.extend(spec.notes)
    lines.append("@enduml")
    return "\n".join(lines) + "\n"


def _specs(prefix: str, names: Iterable[str], members: str = "full") -> tuple[ClassSpec, ...]:
    return tuple(ClassSpec(f"{prefix}.{n}", members) for n in names)


