"""Generate the PlantUML sources that must match the code (P6.1).

Writes into ``docs/diagrams/generated/``:

* ``state.puml`` — the §4 lifecycle, read from the State classes by trying every trigger
  in every state, so the diagram shows exactly the transitions the code allows;
* ``er.puml`` — the database, read from the SQLAlchemy metadata (tables, keys, foreign keys);
* ``class-*.puml`` — class diagrams whose members, inheritance and abstractness are read
  from the classes themselves. Only the associations (which Python cannot tell apart from
  plain attributes) are listed by hand below.

``tests/unit/test_diagrams_fresh.py`` regenerates everything in memory and fails when a
committed file is stale, so a code change that alters a diagram must regenerate it
(``make diagrams``).

Usage: ``uv run python scripts/gen_diagrams.py [OUT_DIR]``.
"""

