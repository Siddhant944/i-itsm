def render_all() -> dict[str, str]:
    """File name -> PlantUML source, for every generated diagram."""
    files = {"state.puml": state_diagram(), "er.puml": er_diagram()}
    for spec in CLASS_DIAGRAMS:
        files[f"{spec.name}.puml"] = class_diagram(spec)
    return files


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT_DIR
    out.mkdir(parents=True, exist_ok=True)
    for name, text in render_all().items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"gen_diagrams: wrote {len(render_all())} files to {out}")


if __name__ == "__main__":
    main()
