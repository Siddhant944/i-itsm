"""Tune the duplicate thresholds on the labelled pairs (blueprint §6.2, P4.1).

    uv run --project backend python scripts/tune_duplicates.py          # print the result
    uv run --project backend python scripts/tune_duplicates.py --write  # and write the report

θ maximises F1 for "is the same underlying problem"; θ-high maximises F1 for "is a
near-identical resubmission". The result goes to docs/testing/duplicates.md. The values the
application uses are the constants in backend/app/domain/similarity.py; a unit test fails when
they drift from what this script finds.
"""

import argparse
import json
import sys
from datetime import timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from app.domain.similarity import (  # noqa: E402
    REJECT_THRESHOLD,
    SUGGEST_THRESHOLD,
    LabelledPair,
    PairMetrics,
    TfIdfEmbeddings,
    best_threshold,
    evaluate,
    score_pairs,
)

FIXTURE = ROOT / "backend" / "tests" / "fixtures" / "duplicate_pairs.json"
REPORT = ROOT / "docs" / "testing" / "duplicates.md"


def load_pairs(path: Path = FIXTURE) -> list[LabelledPair]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return [
        LabelledPair(
            a=item["a"],
            b=item["b"],
            same_service=item["same_service"],
            gap=timedelta(minutes=item["minutes_apart"]),
            duplicate=item["duplicate"],
            repeat=item.get("repeat", False),
        )
        for item in raw["pairs"]
    ]


def _row(name: str, metrics: PairMetrics) -> str:
    return (
        f"| {name} | {metrics.threshold:.2f} | {metrics.precision:.2f} | {metrics.recall:.2f} "
        f"| {metrics.f1:.2f} | {metrics.true_positives} | {metrics.false_positives} "
        f"| {metrics.false_negatives} |"
    )


def render(pairs: list[LabelledPair]) -> tuple[str, PairMetrics, PairMetrics]:
    scores = score_pairs(pairs, TfIdfEmbeddings())
    hybrid = [(score.total, pair.duplicate) for score, pair in zip(scores, pairs, strict=True)]
    text_only = [(score.cosine, pair.duplicate) for score, pair in zip(scores, pairs, strict=True)]
    repeats = [(score.total, pair.repeat) for score, pair in zip(scores, pairs, strict=True)]
    theta, theta_high = best_threshold(hybrid), best_threshold(repeats)
    lines = [
        "# Duplicate detection: thresholds and accuracy",
        "",
        "Generated by `scripts/tune_duplicates.py --write`; do not edit by hand.",
        "",
        f"{len(pairs)} hand-labelled pairs (`backend/tests/fixtures/duplicate_pairs.json`): "
        f"{sum(p.duplicate for p in pairs)} duplicates, of which "
        f"{sum(p.repeat for p in pairs)} are near-identical resubmissions. Scored with the "
        "offline TF-IDF provider, which is what runs when Gemini is unreachable, using the "
        "hybrid score of blueprint §6.2 (β = 0.6, 0.25, 0.15; τ = 2 h).",
        "",
        "| Decision | Threshold | Precision | Recall | F1 | TP | FP | FN |",
        "|---|---|---|---|---|---|---|---|",
        _row("θ: suggest a duplicate (best F1)", theta),
        _row("θ-high: refuse a repeat (best F1)", theta_high),
        _row("In use: θ", evaluate(hybrid, SUGGEST_THRESHOLD)),
        _row("In use: θ-high", evaluate(repeats, REJECT_THRESHOLD)),
        _row("Text alone at 0.60 (the brief's naive rule)", evaluate(text_only, 0.6)),
        _row("Text alone, its own best threshold", best_threshold(text_only)),
        "",
        "The last two rows are why the score is a hybrid: on text alone, a 60 % threshold "
        "misses most paraphrases, including the brief's own INC101-INC103.",
        "",
        "## Every pair",
        "",
        "| # | Score | Text | Same service | Minutes apart | Duplicate | Repeat | A | B |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for number, (pair, score) in enumerate(zip(pairs, scores, strict=True), start=1):
        lines.append(
            f"| {number} | {score.total:.2f} | {score.cosine:.2f} "
            f"| {'yes' if pair.same_service else 'no'} | {int(pair.gap.total_seconds() // 60)} "
            f"| {'yes' if pair.duplicate else 'no'} | {'yes' if pair.repeat else 'no'} "
            f"| {pair.a} | {pair.b} |"
        )
    return "\n".join(lines) + "\n", theta, theta_high


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help=f"write {REPORT.relative_to(ROOT)}")
    args = parser.parse_args()
    report, theta, theta_high = render(load_pairs())
    for name, found, in_use in (
        ("theta", theta, SUGGEST_THRESHOLD),
        ("theta-high", theta_high, REJECT_THRESHOLD),
    ):
        print(f"{name:<10} = {found.threshold:.2f}  F1 {found.f1:.2f}  (in use {in_use})")
    if args.write:
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(report, encoding="utf-8")
        print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
